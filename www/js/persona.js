// 颜文字特征字符（用于检测）
// ⚠️ v1.21.39 修（复审第二轮 新1）：从字符类里拿掉 / \ | ; 和 > <。
//
// 起因：这几个是 ASCII 常见字符，不是颜文字特征。原字符类含它们之后，
// 任何【括号里带斜杠】的正常内容都会被判成颜文字 ——
// stripKaomoji 把【整个括号连同内容】删掉（实跑：
//   「（2024/03/05 更新）这条记录」→「这条记录」
//   「（A/B 测试）结果如下」→「结果如下」
//   「路径是 (C:\Users\test) 这个目录」→「路径是 这个目录」）。
// 触发条件是颜文字档位切到「关闭」——此后每条回复都过这道清洗，
// 删的是已生成文本，还会落库进上下文被她自我模仿。
//
// 连带：hasKaomoji 用同一个 KAO_MARK，kaomojiRate 拿它算「实际使用率」做负反馈。
// 角色一个颜文字没用、只要话里带日期，就会被算成用了 —— 实测 4 条全带斜杠的回复
// 统计出使用率 1.0，bias 变负，越推越不让她用颜文字。
//
// 保留的仍是颜文字专属字符（ω ∀ ´ ` 等），误伤面小得多。
const KAO_MARK = /[・ω∀´`｀╥﹏◍ᴗ꒳๑＾▽￣°∇ΔσΣΦΨΩʖಠὸヮ⌒≧≦〃＊＞＜＼⁄]/;
const PAREN_GRP = /[（(][^\n)）]{1,24}[)）]/g;
const BARE_KAO = /(?:\borz\b|\b233+\b|\bhhh+\b|>_<|T_T|QAQ|QAQQ|www\b)/gi;

/** 检测文本里的颜文字 */
export function detectKaomoji(text) {
  if (!text) return [];
  const found = [];
  const parens = text.match(PAREN_GRP) || [];
  for (const p of parens) {
    if (KAO_MARK.test(p)) found.push(p);
  }
  const bare = text.match(BARE_KAO) || [];
  found.push(...bare);
  return found;
}

export function hasKaomoji(text) {
  return detectKaomoji(text).length > 0;
}

/** 移除颜文字（用于「关闭」档位） */
export function stripKaomoji(text) {
  if (!text) return text;
  let out = text.replace(PAREN_GRP, (m) => (KAO_MARK.test(m) ? '' : m));
  out = out.replace(BARE_KAO, '');
  return out.replace(/[ \t]{2,}/g, ' ').replace(/\n{3,}/g, '\n\n').trim();
}

/** 随机取一个颜文字 */
export function pickKaomoji(style) {
  const lib = KAOMOJI_LIB[style] || KAOMOJI_LIB['jp-soft'];
  return lib[Math.floor(Math.random() * lib.length)];
}

// ---------- 频率闭环控制 ----------

/**
 * 统计最近若干条 AI 消息里，颜文字的实际出现率
 */
export function kaomojiRate(assistantMsgs, lookback = 10) {
  const recent = assistantMsgs.slice(-lookback).filter(m => m.role === 'assistant' && m.content);
  if (!recent.length) return 0;
  const hit = recent.filter(m => hasKaomoji(m.content)).length;
  return hit / recent.length;
}

/**
 * 决定这一轮是否该用颜文字。
 * freq: 0 = 关闭, 1 = 每条都用
 * 用「历史实际频率」和「目标频率」比较，形成负反馈，防止模型一会儿狂用一会儿完全不用。
 */
export function decideKaomoji(freq, historyMsgs) {
  if (!freq || freq <= 0) return false;
  if (freq >= 0.95) return true;
  const actual = kaomojiRate(historyMsgs, 8);
  // 实际偏低 → 更可能要求用；实际偏高 → 压一压
  const bias = freq - actual;
  return Math.random() < Math.min(1, Math.max(0, freq + bias * 0.8));
}

