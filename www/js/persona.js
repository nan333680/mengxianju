const KAOMOJI_ALL = MOOD_ORDER.flatMap(k => KAOMOJI_MOODS[k]);

// 颜文字特征字符（用于检测）
// ⚠️ v1.21.39 修（复审第二轮 新1）：从字符类里拿掉 / \ | ; 和 > <。
//
// 起因：这几个是 ASCII 常见字符，不是颜文字特征。原字符类含它们之后，
// 任何【括号里带斜杠】的正常内容都会被判成颜文字 ——
// stripKaomoji 把【整个括号连同内容】删掉（实跑：
//   「（2024/03/05 更新）这条记录」→「这条记录」
//   「（A/B 测试）结果如下」→「结果如下」
//   「路径是 (C:\Users\test) 这个目录」→「路径是 这个目录」）。
// 触发条件是颜文字档位切到「关闭」——此后每条回复都过这道清洗，
// 删的是已生成文本，还会落库进上下文被她自我模仿。
//
// ⚠️ v0.4.2.3 审计（F11/F15）：判据从「括号里含任一 KAO_MARK 字符」换成
//    「括号组里【全是符号/空白】」—— 老判据问的是「含不含」，不是「像不像」，
//    于是「（笑 ♡）」「（看着你，眼睛有点亮 ♡ 然后移开了视线）」会被整组删掉，
//    括号里的中文一起消失。而 ♡ ♥ ✧ ☺ 这些本来就会出现在正常的括号句里。
//    新判据只把「一个实义字符都没有」的括号当颜文字。
//
//    实义字符 = ASCII 字母数字、平假名/片假名字母（含长音符 ー）、CJK 汉字。
//    ⚠️ 希腊字母（ω σ Δ）与西里尔字母（З）故意【不】算实义 —— 它们是颜文字的常用笔画，
//       而一个正常的括号句里不会只有它们。
//  ⚠️ 假名区要【逐段列】，不能写 \u3040-\u30ff：那一段里混着 U+30FB「・」
//     和 U+30A0「゠」这类【标点】—— 按整段排除的话 (´・ω・`) 会被当成「含假名」
//     而清不掉（实测踩过）。只排假名字母本身 + 长音符 ー。
const SYMBOL_ONLY = /^[^A-Za-z0-9\u3041-\u3096\u30a1-\u30fa\u30fc\u31f0-\u31ff\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]*$/;
const PAREN_GRP = /[（(][^\n)）]{1,24}[)）]/g;
// 裸词颜文字（不带括号的那种）。
// ⚠️ v0.4.2.3 审计（F1）：以前这里还收 orz / 233 / hhh / www ——
//    它们同时是【正常正文】（「笑死 233 了」「他说 www.example.com 上有」「她 orz 了一下」），
//    关闭档位下会被当颜文字删掉、句子破；而 hasKaomoji 又拿它算「她用了颜文字」，
//    于是她说一句 233 就被记一笔，吃进 kaomojiRate 的负反馈、越推越不让她用。
//    现在只留真正不像正常词汇的四个。
const BARE_KAO = /(?:>_<|T_T|QAQ|QAQQ)/g;

/** 检测文本里的颜文字 */
export function detectKaomoji(text) {
  if (!text) return [];
  const found = [];
  const parens = text.match(PAREN_GRP) || [];
  for (const p of parens) {
    if (SYMBOL_ONLY.test(p)) found.push(p);
  }
  const bare = text.match(BARE_KAO) || [];
  found.push(...bare);
  return found;
}

export function hasKaomoji(text) {
  return detectKaomoji(text).length > 0;
}

/** 移除颜文字（用于「关闭」档位） */
export function stripKaomoji(text) {
  if (!text) return text;
  let out = text.replace(PAREN_GRP, (m) => (SYMBOL_ONLY.test(m) ? '' : m));
  out = out.replace(BARE_KAO, '');
  return out.replace(/[ \t]{2,}/g, ' ').replace(/\n{3,}/g, '\n\n').trim();
}

/** 随机取一个颜文字（按心情；表里没有这一档就整库随机） */
export function pickKaomoji(mood) {
  const lib = KAOMOJI_MOODS[mood] || KAOMOJI_ALL;
  return lib[Math.floor(Math.random() * lib.length)];
}

// ---------- 频率闭环控制 ----------

/**
 * 统计最近若干条 AI 消息里，颜文字的实际出现率
 */
export function kaomojiRate(assistantMsgs, lookback = 10) {
  const recent = assistantMsgs.slice(-lookback).filter(m => m.role === 'assistant' && m.content);
  if (!recent.length) return 0;
  const hit = recent.filter(m => hasKaomoji(m.content)).length;
  return hit / recent.length;
}

/**
 * 决定这一轮是否该用颜文字。
 * freq: 0 = 关闭, 1 = 每条都用
 * 用「历史实际频率」和「目标频率」比较，形成负反馈，防止模型一会儿狂用一会儿完全不用。
 */
export function decideKaomoji(freq, historyMsgs) {
  if (!freq || freq <= 0) return false;
  if (freq >= 0.95) return true;
  const actual = kaomojiRate(historyMsgs, 8);
  // 实际偏低 → 更可能要求用；实际偏高 → 压一压
  const bias = freq - actual;
  return Math.random() < Math.min(1, Math.max(0, freq + bias * 0.8));
}

// ⚠️ v0.4.2.3 审计（F22）：emoji 那一侧以前【什么都没有】——
//    档位只改三句话的语气（「可以适度使用」「很少使用」「不要使用」），
//    既没有掷签、也没有负反馈，档位名字却叫「频率」。
//    实测（真调模型 3 次，档位 0.35）：三次回复一个 emoji 都没有；
//    同一批里颜文字档位一开就每次都出现 —— 差别就在这套闭环。
//    现在 emoji 也走同一套：掷签 + 最近实测使用率做负反馈。
const EMOJI_RE = /[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}\u{FE0F}]/u;

/** 统计最近若干条 AI 消息里，emoji 的实际出现率（与 kaomojiRate 同构） */
export function emojiRate(assistantMsgs, lookback = 10) {
  const recent = assistantMsgs.slice(-lookback).filter(m => m.role === 'assistant' && m.content);
  if (!recent.length) return 0;
  const hit = recent.filter(m => EMOJI_RE.test(m.content)).length;
  return hit / recent.length;
}

/** 决定这一轮是否该用 emoji（与 decideKaomoji 同构，见上面的注释） */
export function decideEmoji(freq, historyMsgs) {
  if (!freq || freq <= 0) return false;
  if (freq >= 0.95) return true;
  const actual = emojiRate(historyMsgs, 8);
  const bias = freq - actual;
  return Math.random() < Math.min(1, Math.max(0, freq + bias * 0.8));
}

