/** 时段的显示名。和 app.js 的 CLOCK_PHASES 是一套，但这边不能 import（会成环）。 */
const PHASES = [
  { k: 'dawn',      label: '凌晨' },
  { k: 'morning',   label: '早上' },
  { k: 'forenoon',  label: '上午' },
  { k: 'noon',      label: '中午' },
  { k: 'afternoon', label: '下午' },
  { k: 'evening',   label: '傍晚' },
  { k: 'night',     label: '晚上' },
  { k: 'lateNight', label: '深夜' },
];
const phaseLabel = (k) => (PHASES.find(p => p.k === k) || {}).label || '';

/**
 * 「上一条对话 → 现在」过了多久（C1，2026-09-28 新增）。
 *
 * 为什么要有它：提示词里原本【只有当前时刻】，模型看不到上一条是几点，
 * 历史消息也不带时间。用户手动把 11:24 改成 11:30 之后，她无从知道"过了 6 分钟"，
 * 只能随口说"刚才"或"你昨天发的"。
 *
 * 返回空串的几种情况（宁可不写，也不要给她一个错的数字）：
 *   · 没有上一条 / 没有当前时间
 *   · 同一时段、且没开「精确时间」→ 说不清具体过了多久
 *   · 算出来是负数或零（时间被往回改过）
 *
 * @param {{day?: number, hour?: number, minute?: number, phase?: string}|null} end   当前 clockState
 * @param {{day?: number, hour?: number, minute?: number, phase?: string}|null} start 上一条消息的 story 快照
 * @returns {string} 可以直接拼进 turnNote 的段落，或空串
 */
function clockGap(end, start) {
  if (!end || !start) return '';
  if (typeof end.day !== 'number' || typeof start.day !== 'number') return '';
  const dDay = end.day - start.day;
  if (dDay < 0) return '';
  const hasT = typeof end.hour === 'number' && typeof start.hour === 'number';
  const minOf = (c) => c.day * 1440 + (typeof c.hour === 'number' ? c.hour * 60 + (c.minute || 0) : 0);
  const mk = (c) => '第 ' + c.day + ' 天' + (phaseLabel(c.phase) ? ' ' + phaseLabel(c.phase) : '')
    + (typeof c.hour === 'number'
        ? ' ' + String(c.hour).padStart(2, '0') + ':' + String(c.minute || 0).padStart(2, '0')
        : '');
  // 同一天、同一时段、没精确时刻 —— 什么都没过去，不必写
  if (dDay === 0 && end.phase === start.phase && !hasT) return '';

  let gap;
  if (dDay === 0) {
    if (!hasT) return '';                 // 同一天但时段不同、又没有钟点 → 说不清
    const m = minOf(end) - minOf(start);
    if (m <= 0) return '';
    gap = m >= 60
      ? (m % 60 ? Math.floor(m / 60) + ' 小时 ' + (m % 60) + ' 分钟' : Math.floor(m / 60) + ' 小时')
      : m + ' 分钟';
  } else if (dDay === 1) {
    gap = '一天';
  } else if (dDay < 7) {
    gap = dDay + ' 天';
  } else if (dDay < 30) {
    gap = Math.max(1, Math.round(dDay / 7)) + ' 周';
  } else if (dDay < 365) {
    gap = Math.max(1, Math.round(dDay / 30)) + ' 个月';
  } else {
    gap = Math.max(1, Math.round(dDay / 365)) + ' 年';
  }
  return `\n【上一条对话到现在过了多久】\n`
    + `他上一条是 **${mk(start)}**，现在是 **${mk(end)}**，中间过了 **${gap}**。\n`
    + `就按这个间隔来反应：刚才的事还热着，隔天的就该有"过了一夜"的分寸。`;
}

function fmtTime(d) {
  const wd = ['日', '一', '二', '三', '四', '五', '六'][d.getDay()];
  const hh = String(d.getHours()).padStart(2, '0');
  const mm = String(d.getMinutes()).padStart(2, '0');
  return `${d.getFullYear()}年${d.getMonth() + 1}月${d.getDate()}日 星期${wd} ${hh}:${mm}`;
}

