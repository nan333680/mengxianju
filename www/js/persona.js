/**
 * 「他怎么被称呼、怎么被看待」（v0.5.2）。
 *
 * 为什么要有：正文里怎么称呼用户，以前只能塞在「我的设定」那一大段散文里，
 * 模型于是自由发挥 —— 一会儿叫名字、一会儿叫「用户」、旁白里还写成「他」。
 * 这里是那份散文的【结构化】版本，只影响措辞，不影响情节。
 *
 * ⚠️ 全空返回空串（调用方据此决定要不要 push 这一段）：
 *    默认必须与 v0.5.1 的提示词逐字相同，否则所有老角色的行为都会被动到。
 */
const PRONOUN_LABEL = { he: '「他」', she: '「她」', ta: '「TA」', it: '「它」' };

/**
 * 「你怎么称呼他、怎么看他」的条目本身（v0.5.2.5 从 userAddressBlock 里拆出来）。
 *
 * 拆出来的理由：小说模式要用同一份内容，但标题要由自己那块来控制
 * （小说里这一段叫「你怎么称呼他、怎么看他」，跟聊天一致）。
 * 两处各拼一份字符串 = 以后加字段一定只改一处，最后又变成"聊天里有、小说里没有"。
 *
 * v0.5.3：加 opts.forScene。小说侧【不再】从这里拿指代规则 ——
 * 聊天里「旁白指他用「他」」这句是对的（聊天没有别的旁白规则），
 * 但小说里旁白指代由 scene.js 的 POV 一处决定（旁白「她」/台词「我」/对你「你」）。
 * 两套规则同时进提示词，写出来就是一会儿「他」一会儿「你」。
 * 所以 forScene 时只保留称呼、认知、态度（这些跟指代无关），删掉指代那两行。
 *
 * @param {Object} char 角色
 * @param {Object} s 设置
 * @param {{forScene?: boolean}} [opts]
 * @returns {string[]} 每条一行（不带标题、不带小标题说明）；全空返回 []
 */
export function userSideLines(char, s, opts) {
  const o = (opts && typeof opts === 'object') ? opts : {};
  const c = char || {}, st = s || {};
  const name = String(st.userName || '').trim();
  const pron = String(st.userPronoun || 'you');
  const ident = String(st.userIdentity || 'lead');
  const addrD = String(st.userAddressDefault || '').trim();
  const cAddr = String(c.userAddress || '').trim();
  const perc = String(c.userPerception || '').trim();
  const know = String(c.userKnowledge || '').trim();
  const att = String(c.userAttitude || '').trim();
  const lines = [];
  if (name) {
    lines.push('- 他的名字是「' + name + '」。你要时可以直接叫这个名字，但不必每句都叫 —— 大多时候还是说「你」。');
  }
  const addr = cAddr || addrD;
  if (addr) {
    lines.push('- 你叫他「' + addr + '」。这是你对他的固定叫法，别换成别的称呼。');
  }
  const pl = PRONOUN_LABEL[pron];
  if (o.forScene) {
    // 小说侧：指代交给 scene.js 的 POV，这里一个字都不说（连带 name 那半句）
  } else if (pl) {
    lines.push('- 旁白里指他用 ' + pl + '（不要写成「你」以外的性别，也不要写成「用户」）。');
    lines.push('- 你的台词里永远说「你」，不要把旁白那个第三人称带进说出来。');
  } else if (pron === 'name') {
    lines.push('- 旁白里指他就直接用名字，不用代词。你的台词里还是说「你」。');
  }
  if (ident === 'off') {
    lines.push('- 这个故事里他不在场。不要把他在场写成既定事实，也别替他安排动作。');
  } else if (ident === 'side') {
    lines.push('- 他是这个场子里的人，但不是主角。别把注意力一直挂在他身上。');
  }
  if (perc) lines.push('- 你以为他是：' + perc);
  if (know) lines.push('- 关于他，你知道 / 不知道：' + know);
  if (att) lines.push('- 你对他：' + att);
  return lines;
}

/**
 * 聊天侧用的完整块（带标题与说明）。
 *
 * ⚠️ 全空返回空串（调用方据此决定要不要 push 这一段）：
 *    默认必须与 v0.5.1 的提示词逐字相同，否则所有老角色的行为都会被动到。
 */
function userAddressBlock(char, s) {
  const lines = userSideLines(char, s);
  if (!lines.length) return '';
  return '# 你怎么称呼他、怎么看他\n'
    + '（这一节只管措辞和认知，不改变任何情节。空着的事就是【你不知道】，不要替他补。）\n'
    + lines.join('\n');
}
export function buildStablePrompt(char, s, constWb) {
  const parts = [];

  // ⚠️ 群聊时标题不能写「你的角色设定」（v0.4.0 复查，群聊诊断文档 缺陷 1 的第 3 条）。
  //    群里 char.persona 是 composeGroupPersona 拼出来的【名单 + 每个人的设定】，
  //    开头是"你们是「周末茶会」里的人" —— 标题却写着"你的角色设定"，
  //    模型读到的意思变成"我就是这一整群人"，这正是 SillyTavern 官方
  //    对 Join 模式警告的那句：characters being confused about themselves。
  //    换成"这个场合"之后它是一份【背景介绍】，不是"你是谁"。
  const isGrp = !!(char && char.isGroup === true && Array.isArray(char.memberIds));
  parts.push(isGrp
    ? `# 这个场合\n${char.persona || '（这个群还没有设定）'}\n\n${GROUP_USE}`
    : `# 你的角色设定\n${char.persona || '你是一个友好的聊天伙伴。'}\n\n${SOLO_USE}`);

  // —— 卡里另外那几项（v0.4.2）——
  // 起因（用户复核）：从 chub 导进来的卡里 personality / scenario / mes_example /
  // system_prompt / post_history_instructions 这几项【读出来了但一个字都没用】，
  // 于是"她"少了半个人，而且导入时的提示里也不提。
  // 现在按标签拼在设定后面：它们是设定的一部分，不是"附加信息"。
  // ⚠️ 不进 char.persona 本体（那样再导出会变成 description 里塞了一堆标签，
  //    往返一次就膨胀一次）—— 只在这里拼给模型看。
  if (!isGrp && char && char.cardFields && typeof char.cardFields === 'object') {
    const cf = char.cardFields;
    const blocks = [];
    if (cf.personality) blocks.push('【性格】\n' + cf.personality);
    if (cf.scenario) blocks.push('【场景】\n' + cf.scenario);
    if (cf.mesExample) blocks.push('【对话范例】\n' + cf.mesExample + '\n（照这个的写法说话：格式、长度、动作和台词的排布都参照它）');
    if (cf.systemPrompt) blocks.push('【卡里给的角色说明】\n' + cf.systemPrompt);
    if (cf.postHistory) blocks.push('【对话之后要一直记着的】\n' + cf.postHistory);
    if (blocks.length) parts.push('# 卡里另外带来的设定\n' + blocks.join('\n\n'));
  }

  // ⚠️ 「外貌」（你此刻的样子）【挪到了本函数最末尾】（v1.21.42）。
  //
  // 原来它固定在角色设定之后（第 2 位），旧注释的理由是
  // 「只要这一段在，前面的内容没变，缓存就照样命中」—— 这话只说对了一半：
  // 前缀缓存是【从头往后匹配、遇到第一个不同就停】，前面确实能命中，
  // 但这一段一变，它【后面所有内容全部作废】。
  //
  // 而它偏偏是这个函数里最常改的一项 —— 用户随时改外貌，
  // 还有个「立即生效」按钮专门用来即时覆盖。它排在越前面，
  // 每次改就把越多东西（关于对方 / 他住的地方 / 表达方式 / 视角 / 关于括号）重新计费。
  //
  // 规则：变化越频繁的越靠后。它现在在最末。

  // —— 常驻世界书（v1.21.51）——
  // 位置：角色设定之后、「关于对方」之前：先知道你是谁，再知道你们在什么世界里，
  // 最后才是"对方是个什么样的人"。
  //
  // ⚠️ 只有【每轮都在】的常驻条目（世界书里那档「基础设定」）能进这里。
  //    靠关键词命中才注入的条目一旦进了稳定前缀，就等于每轮改一次前缀 ——
  //    缓存全废、token 翻十倍（见 buildTurnNote 里世界书那段的实测数字）。
  const constWbList = (Array.isArray(constWb) ? constWb : []).filter(x => x && x.content);
  if (constWbList.length) {
    const body = constWbList.map(h => '【' + (h.title || '设定') + '】\n' + h.content).join('\n\n');
    parts.push('# 基础设定\n'
      + '（这些是这个世界的底色，一直成立、不用复述；跟它们冲突时以它们为准。）\n\n'
      + body);
  }

  // —— 后来补的设定（v0.5.3）——
  // 起因：用户问过「后续补的设定能不能进记忆」。答案是【不能】——
  //   记忆会被取代（同槽位新说法顶掉旧的）、会过期、还会被预算裁掉，
  //   而设定必须一直稳定成立。所以给它单独一个家：char.canonExtra。
  // 位置：常驻世界书之后、「关于对方」之前 —— 它压在世界书上面，
  //   因为它就是"这个角色后来改过的主张"，比通用世界设定更该被听见。
  const canonExtra = String((char && char.canonExtra) || '').trim();
  if (canonExtra) {
    parts.push('# 后来补的设定\n'
      + '（这些是后来补的；和角色卡冲突时以这里为准。只对当前角色生效。）\n\n'
      + canonExtra);
  }

  // 「我的设定」：全局一份，所有角色共用。放在角色设定之后 ——
  // 这样她先知道自己是谁，再知道"对方是个什么样的人"。
  // ⚠️ v1.21.47：这一段从"全局一份"改成【角色级】—— 每个角色对"你是谁"可以有自己的理解。
  //    char.myProfile 还没设时回落全局那份：那是老数据的一次性兜底
  //    （迁移见 app.js 的 migrateGlobalProfileToChars）。
  const profile = String((char && char.myProfile !== undefined && char.myProfile !== null)
    ? char.myProfile : (s.myProfile || '')).trim();
  if (profile) {
    parts.push(`# 关于对方\n（这是他自己的说明，请一直记着）\n${profile}`);
  }

  // 「我的居住环境」：全局一份，讲清"他住的地方长什么样"。
  // 紧跟在「关于对方」后面：先说人，再说人待的地方，读起来是一路的。
  //
  // 加它的原因：模型没有环境设定时会自由发挥——凭空编窗外、编房间、编天气，
  // 跟用户实际的情况打架。长期记忆拦不住，因为记忆记的是"事件"，不是"环境"。
  // 同上（v1.21.47）：角色级优先，没设过才回落全局
  const env = String((char && char.myEnv !== undefined && char.myEnv !== null)
    ? char.myEnv : (s.myEnv || '')).trim();
  if (env) {
    // ⚠️ 加一条【仲裁语】（v1.21.33）：
    // 起因（用户提问）：世界书里也有「他的房子」这类词条时，两条会打架。
    // 而原来这条写的是「写到他家、房间、窗外、周边环境时【以此为准】」——
    // 世界书那边写的是「供你理解世界，不必主动复述」，措辞一硬一软，
    // 加上本段在【稳定前缀】（位置更靠前、更"根"），实测世界书会被压过去。
    // 现在显式声明优先级：专写住处的世界书条目 > 这条通用设定。
    parts.push(`# 他住的地方\n` +
      '（这是他居住环境的设定，和上面关于他的说明是一套。' +
      '写到他家、房间、窗外、周边环境时以此为准；' +
      '但【如果世界书里专门写了他的房子/住处/房间，以世界书那条为准】——' +
      '那条是他为这个地方单独写的，比这里的通用设定更准。' +
      '【没有写到的地方不要自己编】——不确定就写得模糊一点，' +
      '不要凭空添加这里没有的房间、家具、天气、外面的景物。）\n' + env);
  }

  // 称谓（v0.5.2 · 小说模式的称谓层，聊天里也用）：她怎么叫他、旁白怎么指他。
  // ⚠️ 只有真填过才有这一段 —— 全空时一个字符都不出现，老角色的提示词完全不变。
  const addrLines = userAddressBlock(char, s);
  if (addrLines) parts.push(addrLines);

  const exp = [];
  const freq = effKaomojiFreq(char, s);

  if (freq <= 0) {
    exp.push('- 你不使用任何颜文字（如 (´・ω・`) 这类符号组合）。');
  } else {
  // ⚠️ v0.4.2.2：原来是「你习惯的风格是X，常用的是这一类：<4 条>」—— 按【风格】给样例，
  //    而用户要的是「按当下的心情挑」。四个风格在模型眼里几乎没差别，结果它每轮都从
  //    同一小撮里拿，表情永远一个样（用户实测反馈）。
  //    现在给的是【按心情分好的整张表】，并要求它先判断自己这会儿的心情、
  //    再从对上号的那一组里挑。风格降级成「口味」：只影响语气，不是挑选依据。
  {
    const rows = MOOD_ORDER.map(k => {
      const kk = (KAOMOJI_MOODS[k] || []).slice(0, 5).join(' ');
      const ee = (EMOJI_MOODS[k] || []).slice(0, 3).join('');
      return '  ' + MOOD_NAME[k] + '：' + kk + (ee ? '　' + ee : '');
    });
    exp.push('- 你想加颜文字的时候，先看自己这会儿是什么心情，再从下面【对上号的那一组】里挑一个：\n'
      + rows.join('\n') + '\n'
      + '- 挑的时候守三条：① 一条消息顶多加一个颜文字；② 表里没有对得上你心情的就不用，'
      + '别自己造、也别用表里没有的符号（有些字符手机上没有，会显示成一个方框）；'
      + '③ 不要连着两条用同一个。');
  }
  }

  const ef = s.emojiFreq ?? 0;
  if (ef <= 0) exp.push('- 不要使用 emoji 表情符号。');
  else {
    // freq>0 时上面那张心情表每行尾巴上已经带了 3 个 emoji，这里就不再重复贴一遍表。
    const head = ef < 0.3
      ? '- 很少使用 emoji，偶尔一两个即可。要用就从上面那张表里对上心情的那一组里挑。'
      : '- 可以适度使用 emoji：一条消息最多两个，别当句末标点连着排。要用就从上面那张表里对上心情的那一组里挑。';
    if (freq > 0) exp.push(head);
    else {
      const erows = MOOD_ORDER.map(k => '  ' + MOOD_NAME[k] + '：' + (EMOJI_MOODS[k] || []).slice(0, 3).join('')).join('\n');
      exp.push(head.replace('上面那张表', '下面这张表') + '\n' + erows);
    }
  }

  exp.push('- ' + (LEN_HINT[s.verbosity] || LEN_HINT.medium));

  // 长篇档的结构要求（v0.5.5）：只在「长篇」这一档注入。
  // 别的档位下她就是在发消息，硬塞分段/落点只会把日常对话写歪。
  if (s.verbosity === 'epic') {
    exp.push('这一条按【长篇】的要求写：');
    for (const line of LONG_PROSE) exp.push('- ' + line);
  }

  // 反客服腔（v0.5.5）：所有档位都生效。
  for (const line of ANTI_SERVICE) exp.push('- ' + line);

  // 非对话描写：和上面的"回复长度"是两个独立上限。
  // 先讲清括号是干什么的，再说这一档写多细。
  //
  // ⚠️ 这里那句"两个上限各算各的"不能省。
  // 起因（用户实测反馈）：只给两条上限、不说它们互不占用时，模型会把
  // "说出口的话 150 字"当成【整条消息的总长度】，于是括号先把配额吃掉，
  // 表现就是"括号字数按最大那档算"。必须显式声明两者分开计数。
  const descLevel = s.descLevel || 'mid';
  const descLines = DESC_HINT[descLevel] || DESC_HINT.mid;
  if (descLevel === 'off') {
    exp.push('- 上面那条【说出口的话】的长度上限，和括号【完全分开算】——'
           + '括号不算在里面，也不会占用它的名额。');
    exp.push('- 这一档下【整条消息里不出现括号】，所以上面那个上限就是这条消息的全部内容。');
  } else {
    exp.push('- 上面那条【说出口的话】的长度上限，只管括号外面的部分。');
    exp.push('- 括号里写多少，由下面这条【单独】决定，不会占用上面那个名额；'
           + '反过来，括号写得多也不会让说出口的话变长。');
    exp.push('- 写法：括号里写动作、神态、语气、环境，括号外面才是你说出口的话。');
  }
  for (const line of descLines) exp.push('- ' + line);

  // 描写驱动力（v1.21.31 新增）：和 descLevel 并列，管【结构】不管【上限】。
  // ⚠️ descLevel === 'off' 时整条消息不许有括号 —— 那时这个开关无从谈起，跳过。
  //
  // ⚠️ v0.4.3.3：这里原来有一层【字数预算降档】——
  //   DESC_HINT 的硬上限（8/25/60 字）配一张 DRIVE_NEED（各驱动档写全要多少字），
  //   撑不下就把驱动【静默降成 low】，并在提示词里写「按最低档执行，别写长」。
  //
  // 用户实测后明确要求【不要档位与固定字数绑定】，这一层已整体删除：
  // 起因是他把三个档都调高（verbosity=long / detailDrive=high），
  // 却发现输出没变长 —— 因为 descLevel 停在「中」（每括号 25 字），
  // 而 high 需要 45 字 → 被静默降成 low，他选的「详」从来没有进过提示词，
  // 界面上却一直显示「详」。这是不可发现的行为偏差，比"指令稍有冲突"更糟。
  //
  // 现在两个开关【各自独立生效】，冲突时由模型自己裁剪，
  // 提示词只给一条不涉及具体数字的兜底（写不下就只写最关键的那一件）。
  const drive = s.detailDrive || 'off';
  const driveLines = DETAIL_DRIVE[drive] || DETAIL_DRIVE.off;
  if (driveLines.length && descLevel !== 'off') {
    exp.push('- 下面几条只管【括号里怎么写】，上面那个长度上限照旧生效。');
    exp.push('- 要是下面要的东西一次装不下，就只写最关键的那一件、把它写到位，不要样样都摊薄。');
    for (const line of driveLines) exp.push('- ' + line);
  }

  if (s.splitMessages) {
    exp.push(`- 可以把一句话拆成 2-${s.splitMax || 3} 条短消息来发，每条之间用单独一行 \`---\` 分隔，模拟真人连着发几条。`);
  } else {
    exp.push('- 一次只发一条消息，不要用 --- 分隔。');
  }

  if (s.hesitation) {
    exp.push('- 适当用「……」表示停顿和迟疑，让语气更自然。'
           + '但它只能夹在句子里（「我……不知道」），【不能整条消息只有它】。');
  }

  // 【沉默必须写出来】（v1.21.22）。
  //
  // 起因（用户实测，反复出现）：她在"这时候不该说话"的戏里会整条只回一个「……」。
  // 用户看到的是一次次空白，只能不停点「重新思考」——
  // 而重试往往还是省略号，因为那是模型【主动】选的，不是被截断。
  //
  // 为什么会这样：角色Q 那种人设本来就写着她可以沉默；thinkMode 开着时对方整条
  // 都在括号里 = 他什么都没说；再叠上「hestitation 允许用省略号」的提示，
  // 模型就得出结论：此刻没有可说的话 → 输出省略号。
  // 实测那条的 reasoning 占了 completion 的 100%（155/155），全花在纠结上。
  //
  // 关键区分：【可以没有话说，但必须有内容】。
  // 不说话 ≠ 不回复。她要写的是"她怎么不说话"——
  // 平静地看着、把茶推过去、偏过头、屋里安静下来、她心里那一下是什么。
  // 这条对所有角色生效：它的意图是"别留白"，和具体人设无关。
  exp.push('- 【绝不允许】整条消息只有一个省略号、一个标点、或一片空白。');
  exp.push('- 就算你这时候【不该说话】——被捂住了嘴、不想开口、他没问你——也要写出来：'
         + '你在做什么、看着什么、手放在哪儿、屋里什么样、你心里那一下是什么。');
  exp.push('- 【不说话 ≠ 不回复】。你要写的是「你怎么不说话」，不是留一片空白。');
  // ⚠️ 这里【绝对不能给"最少写什么"的示例】（v1.21.23 修）。
  //
  // 第一版写的是「哪怕只是『（平静地看着他，没开口）』，也比一个省略号强得多」。
  // 用户实测评价：【太人机了，不如不输出】——
  // 那句"哪怕只是"在人类读来是下限，模型读来是【照这个写就对了】。
  // 于是她真的一路「平静地看着他」，比省略号还糟。
  //
  // 教训：给模型举例时，【它会把例子当成标准答案】。
  //       想要下限就描述"什么算不合格"，不要示范"勉强合格的样子"。
  // ⚠️ descLevel=off 时整组跳过（v0.5.0.1 复查）：这一档上面明写
  //    「整条消息里不出现括号」「不要写括号里的动作/神态描写」，
  //    下面这几条却全在教她括号里该怎么取材 —— 自相矛盾，还会把注意力引回括号。
  if (descLevel !== 'off') {
  exp.push('- 【注意】「（平静地看着他）」这种写法【信息量为零】——谁都写得出来，'
         + '不构成回复。要写就写【只有你才会有的那一下】：嘴角那点没压下去的意思、'
         + '故意慢半拍的呼吸、手指在袖口上捻了一下、心里冒出来又咽回去的那句。');
  // ⚠️ 补【取材方法】（v1.21.30，复审省略号专项 B）。
  //
  // 起因：上面的硬约束只有「不许写什么」（否定式），没有「那该写什么」（正面锚点）——
  // 模型知道不该留白，却缺锚点，于是【自己收敛到最安全、最通用的那句】：
  // 实测用户库里仅存的 2 条残留正是 `（只是看着他，没有开口）` ——
  // 那恰恰是 403 行被否掉的那句「人机句」。
  //
  // ⚠️ 但【不能给句式示范】（403-409 的教训：模型会把例子当标准答案）。
  // 这里给的是【取材方法】（从哪儿找内容）+【堵死它自己找到的收敛目标】，
  // 方向与 403 的教训相反、作用互补。
  exp.push('- 想不出写什么时，从这三处里挑一样写：① 你此刻在做什么（手放在哪儿、'
         + '身体什么姿势、周围什么样）；② 你看见他哪一点（他刚做了什么、什么表情）；'
         + '③ 你心里冒出来又咽回去的那句（写成「没说出口」，不要写成台词）。');
  exp.push('- 这三样都找不到，才说明这一轮真的没有可写的——那就把「没得写」本身写出来，'
         + '不要交一个省略号。');
  exp.push('- 【不要写】「（只是看着他，没有开口）」这一类——它对任何角色、任何场景都成立，'
         + '等于什么都没说。');
  }
  // ⚠️ 【公式化：收尾与让步】（v0.4.3.1 加）。
  //
  // 实测来源（她 2026-10-16 备份里的同一份 157 条 assistant 语料）：
  //   87% 收在台词上，其中 14%（22 条）是 ≤6 字的判词（「这就对了」「知道了」「行了」）；
  //   「我认 / 这话我认 / 我认了」跨 8 个角色共 43 次（紫 14 / 早苗 7 / 文 6 / 芙兰 5 …）。
  // 用户实测对照（豆包 / GPT 承认时不会这么说）确认：这是模型自己的口头习惯，不是人设，
  // 所以放在公共层，不加进任何角色卡。
  //
  // ⚠️ 仍然只写【什么算不合格】（上面那条举例的教训：给例子 = 给标准答案）。
  exp.push('- 【不合格】用两三个字的短句收尾（' + LQ + '这就对了' + RQ + LQ + '知道了' + RQ + LQ + '行了' + RQ
         + ' 这一类）——收尾要么把话说完，要么停在动作上，不要每次都甩一句判词。');
  exp.push('- 【不合格】表示「行、随你」的时候每次都收在同一个词上（' + LQ + '我认' + RQ
         + ' 这一类说法整段对话里出现一次就够）——上一轮是怎么松口的，这一轮换一句说。');

  // ⚠️ 【句式与标点】（v0.4.3.2 加，用户拍板把外部建议那六条全做）。
  //
  // 四条都不给范句 —— 理由同上：给例子 = 给标准答案，她会照着样子写
  // （persona.js:812 那条「平静地看着他」的教训就是这么来的）。
  // 同上：这两条讲的全是括号里的句式，off 档没有括号，跳过。
  if (descLevel !== 'off') {
  exp.push('- 【不合格】括号里用分号把一串小动作硬串成一句（三件事之间全是「；」）——'
         + '括号里也在聊天，一件事一句话，读起来要顺；分号一整条消息里出现一次都算多。');
  exp.push('- 【不合格】每条回复都先用括号开头、再接口词 —— 偶尔让话先说、动作跟在后面，'
         + '或者整条就只有一句话。');
  }
  exp.push('- 【不合格】把前几轮用过的句子原样再写一遍（同一个比喻、同一个动作、同一句词，'
         + '换个标点又出现一次）——同一个说法整段对话里用一次就够，第二次换个说法说同一件事。');
  exp.push('- 【不合格】通篇都是句号，连该问的地方也是平的 —— 标点跟着语气走；'
         + '但也别为了显得有情绪而堆叹号。');

  exp.push('- 用口语聊天，不要用书面语、不要列 1234 条、不要写小标题、不要总结。');
  exp.push('- 不要提及自己是 AI、模型或程序。');

  parts.push(`# 表达方式\n${exp.join('\n')}`);

  // 视角锁定：单独成段放在最后，权重最高（模型对靠后的指令更敏感）。
  // 只在角色开了这个开关时才写，关着的时候提示词和以前完全一样（缓存不受影响）。
  // 叙事视角（v1.21.48）：'L1'~'L4' 四档；空 / 未设 = 不注入任何视角段落。
  //
  // ⚠️ 老数据的两条映射必须「一个字都不变」，因为这两段都在稳定前缀里：
  //    povLock=true  → L1（就是原来的 POV_HINT，逐字相同）
  //    povLock=false → 不注入（原来也是不注入）
  //    最容易写错的是把 false 也塞进 L1 —— 那等于给所有关着锁的角色凭空加了约束。
  const povKey = (s.povStyle && POV_STYLES[s.povStyle]) ? s.povStyle : (s.povLock ? 'L1' : '');
  if (povKey) {
    parts.push(`# 视角\n${POV_STYLES[povKey].join('\n')}`);
  }

  // 强制聊天模式：掰正"括号的语义"。
  // 和 povLock 一样放稳定前缀：它是长期规则、不随轮次变，
  // 开关不动时提示词逐字一致，前缀缓存照样命中（放变化段反而每轮都失效）。
  if (s.thinkMode) {
    parts.push(`# 关于括号\n${THINK_HINT.join('\n')}`);
  }

  // 「外貌」：她此刻的穿着和状态（角色级，随时会改）—— 【放最末尾】（v1.21.42）。
  //
  // 放最后的理由见本函数开头那段注释：它是这里变化最频繁的一项，
  // 一变就把它【后面】的全部作废。放末尾则改它只作废它自己。
  //
  // 空着 = 完全不注入，老角色的提示词一个字都不变。
  // 开关关掉 = 内容留着但也不注入（用户临时不想让她知道当前状态时用）。
  // 两层：appearanceLive（「立即生效」的临时覆盖）优先于 appearance（「保存」的长期基线）。
  // Live 为空时自动回落，所以用户点「清除」就等于回到长期那份。
  const look = ((s.appearanceLive || '').trim() || (s.appearance || '').trim());
  if (look && s.appearanceOn !== false) {
    parts.push(`# 你此刻的样子\n` +
      '（这是你现在身上穿的和当前的状态，【优先级最高】。' +
      '你设定里提到的服装是平时或别的场合的样子，此刻一律以这段为准；' +
      '两处不一致时，按这段写，不要按设定里那套写。）\n' +
      '写动作、神态、描写时也以此为准，不要写出和这里矛盾的东西' +
      '——比如这里说你没穿外套，就不要写拉外套的领子。\n' + look);
  }

  return parts.join('\n\n');
}

/**
 * 【本轮段】会变化的内容：记忆 / 时间 / 这一轮要不要颜文字
 * 放在消息列表的**最后**，这样前面的稳定前缀仍然能命中缓存
 */
/**
 * 一年按多少天算（v1.21.43）。
 *
 * ⚠️ 这只是【显示用的换算率】，day 才是唯一的数据源 —— 不新增 year 字段。
 *    两套数并存迟早对不上（改了年没改天，或者反过来）。
 */
export const DAYS_PER_YEAR = 365;

/**
 * 天数的显示文案（v1.21.43 起大跨度带「年」）。
 *
 * 为什么要有它：天数上限放宽到 9999999 之后，「第 365250 天」这种写法
 * 读起来没有尺度感 —— 看到「第 1001 年 250 天」才知道这是千年之后的事。
 *
 * ⚠️ day ≤ 365 时【一个字都不改】，和以前完全一样。这一条很重要：
 *    提示词里的时间串参与前缀缓存，老角色（天数都小）不能因为这次改动而失配。
 *
 * 换算：第 1 年 = 第 1~365 天，第 2 年 = 第 366 天起（所以是 (d-1)/365 而不是 d/365）。
 *
 * 放在 persona.js 而不是 app.js：提示词里两处都要用它（"现在的时间"和下面的锚点表），
 * 分开写两份迟早会漂移。
 */
export function dayLabel(day) {
  const d = Math.max(1, Math.floor(Number(day) || 1));
  if (d <= DAYS_PER_YEAR) return '第 ' + d + ' 天';
  const y = Math.floor((d - 1) / DAYS_PER_YEAR) + 1;
  const rest = ((d - 1) % DAYS_PER_YEAR) + 1;
  return '第 ' + y + ' 年 ' + rest + ' 天';
}

/**
 * 把话题切成"用来比对的词"（v1.21.56）。
 * 中文没有空格，用【二元组】—— 「咖啡店」→ 咖啡/啡店，够用且不需要分词库。
 * 英文/数字按整词。返回 Set，方便 O(1) 判重。
 */
function topicGrams(topic) {
  const s = String(topic || '');
  const out = new Set();
  for (const chunk of (s.match(/[\u4e00-\u9fff]+/g) || [])) {
    if (chunk.length === 1) out.add(chunk);
    for (let i = 0; i + 1 < chunk.length; i++) out.add(chunk.slice(i, i + 2));
  }
  for (const w of (s.match(/[A-Za-z0-9]{2,}/g) || [])) out.add(w.toLowerCase());
  return out;
}

/**
 * 从记忆里挑出【跟眼下这段话最相关】的那几条（v1.21.56）。
 *
 * 以前是 memories.slice(-24)：纯按最新。这套在几十轮内没问题，
 * 几百轮之后就成了"她记得结论、细节对不上"——你正在聊的那件事被更晚的 24 条挤在外面。
 *
 * 不上向量检索（要引依赖、还要每轮算 embedding）：先做**关键词重合 + 新近度 + pinned**。
 *   相关度 = 命中词数 × 3      ← 主导项
 *   pinned = 用户点名要记的 × 2 ← 那是他明确要求记住的，不该被挤掉
 *   新近度 = 越靠后越大 × 0.5   ← 只做微调
 * ⚠️ 新近度权重刻意压得很低：给高了会把"最近但无关"的顶上来，等于回到老行为。
 *
 * @param {Array} memories 记忆数组（按时间追加，最后一条最新）
 * @param {string} topic 眼下这段话（一般是本轮用户输入 + 最近一两条）
 * @param {number} limit 取几条（默认 24，与旧行为一致）
 * @returns {Array} 挑出来的记忆，**按原时间顺序**排回去（注入给模型的文本读起来才不乱）
 */
export function rankMemories(memories, topic, limit = 24) {
  const list = Array.isArray(memories) ? memories : [];
  if (!list.length) return [];
  // 本来就不超过上限 → 不折腾（也避免了"打分把顺序打乱"这种没必要的副作用）
  if (list.length <= limit) return list.slice();
  // ⚠️ pinned 是【保底进】，不参与打分争夺（v1.21.56 第一版就栽在这儿）。
  //
  // 起初把它做成 +2 分的加成，可"关键词命中"一条就是 +3 ——
  // 话题里只要凑够 24 条沾边的记忆，用户点名要记住的那条就会被挤出去。
  // 实测：记忆里有 29 条含「无关」的旧事、当轮话题里也有「无关」，
  // 那条 pinned 就排到了第 30 名、直接落选。
  // 「记住这个」是他明确下的指令，不该输给任何打分。
  const isPinned = (m) => !!(m && m.freq === 'pinned');
  const pinnedList = list.filter(isPinned);
  const pinnedSet = new Set(pinnedList);
  const rest = list.filter(m => !pinnedSet.has(m));
  const room = Math.max(0, limit - pinnedList.length);   // pinned 先占名额，剩下的才打分
  const grams = topicGrams(topic);
  const scored = rest.map((m, i) => {
    const text = String((m && m.text) || '');
    let hit = 0;
    for (const g of grams) if (text.includes(g)) hit++;
    // 新近度权重刻意压得很低：给高了会把"最近但无关"的顶上来，等于退回老行为
    const recency = rest.length > 1 ? i / (rest.length - 1) : 1;
    return { m, i, score: hit * 3 + recency * 0.5 };
  });
  // 同分时按原始顺序（稳定，不会因为排序实现不同而抖）
  scored.sort((a, b) => (b.score - a.score) || (a.i - b.i));
  const keep = new Set(pinnedList);
  for (const x of scored.slice(0, room)) keep.add(x.m);
  return list.filter(m => keep.has(m));   // 按原时间顺序回去
}

