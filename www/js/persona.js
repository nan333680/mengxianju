      + (gapText && !gapBack
        ? `· 隔了这么久，手头那件小事（洗澡、吃饭、走路）通常已经做完了——别把一个动作停在上一次那一下。`
          + `  但他要是明说还在做，就以他说的为准。\n`
        : '')
      + `· ⚠️ 【不要自己编数字】。他没说多久，你就不要替他算出一个具体分钟数。`
      + `  可以说「好一阵」，不要说「二十三分钟」。\n`
      + `· 如果他写的时间和上面的设定对不上（明明才过了一会儿，却说到第二天了），以上面那个为准；`
