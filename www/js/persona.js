/** 取角色实际生效的颜文字频率 */
function effKaomojiFreq(char, s) {
  return (char.kaomojiFreq !== null && char.kaomojiFreq !== undefined)
    ? char.kaomojiFreq
    : (s.kaomojiFreq ?? 0.15);
}

/**
 * 【稳定段】角色设定 + 基础表达规则
 * 内容不随轮次变化 —— 保持完全一致才能命中 DeepSeek 的前缀缓存（省一个数量级）
 * 不要往这里面放时间、随机值、每轮变化的东西
 */
export function buildStablePrompt(char, s, constWb) {
  const parts = [];

  // ⚠️ 群聊时标题不能写「你的角色设定」（v0.4.0 复查，群聊诊断文档 缺陷 1 的第 3 条）。
  //    群里 char.persona 是 composeGroupPersona 拼出来的【名单 + 每个人的设定】，
  //    开头是"你们是「周末茶会」里的人" —— 标题却写着"你的角色设定"，
  //    模型读到的意思变成"我就是这一整群人"，这正是 SillyTavern 官方
  //    对 Join 模式警告的那句：characters being confused about themselves。
  //    换成"这个场合"之后它是一份【背景介绍】，不是"你是谁"。
  const isGrp = !!(char && char.isGroup === true && Array.isArray(char.memberIds));
  parts.push(isGrp
    ? `# 这个场合\n${char.persona || '（这个群还没有设定）'}`
    : `# 你的角色设定\n${char.persona || '你是一个友好的聊天伙伴。'}`);

  // ⚠️ 「外貌」（你此刻的样子）【挪到了本函数最末尾】（v1.21.42）。
  //
  // 原来它固定在角色设定之后（第 2 位），旧注释的理由是
  // 「只要这一段在，前面的内容没变，缓存就照样命中」—— 这话只说对了一半：
  // 前缀缓存是【从头往后匹配、遇到第一个不同就停】，前面确实能命中，
  // 但这一段一变，它【后面所有内容全部作废】。
  //
  // 而它偏偏是这个函数里最常改的一项 —— 用户随时改外貌，
  // 还有个「立即生效」按钮专门用来即时覆盖。它排在越前面，
  // 每次改就把越多东西（关于对方 / 他住的地方 / 表达方式 / 视角 / 关于括号）重新计费。
  //
  // 规则：变化越频繁的越靠后。它现在在最末。

  // —— 常驻世界书（v1.21.51）——
  // 位置：角色设定之后、「关于对方」之前：先知道你是谁，再知道你们在什么世界里，
  // 最后才是"对方是个什么样的人"。
  //
  // ⚠️ 只有【每轮都在】的常驻条目（世界书里那档「基础设定」）能进这里。
  //    靠关键词命中才注入的条目一旦进了稳定前缀，就等于每轮改一次前缀 ——
  //    缓存全废、token 翻十倍（见 buildTurnNote 里世界书那段的实测数字）。
  const constWbList = (Array.isArray(constWb) ? constWb : []).filter(x => x && x.content);
  if (constWbList.length) {
    const body = constWbList.map(h => '【' + (h.title || '设定') + '】\n' + h.content).join('\n\n');
    parts.push('# 基础设定\n'
      + '（这些是这个世界的底色，一直成立、不用复述；跟它们冲突时以它们为准。）\n\n'
      + body);
  }

  // 「我的设定」：全局一份，所有角色共用。放在角色设定之后 ——
  // 这样她先知道自己是谁，再知道"对方是个什么样的人"。
  // ⚠️ v1.21.47：这一段从"全局一份"改成【角色级】—— 每个角色对"你是谁"可以有自己的理解。
  //    char.myProfile 还没设时回落全局那份：那是老数据的一次性兜底
  //    （迁移见 app.js 的 migrateGlobalProfileToChars）。
  const profile = String((char && char.myProfile !== undefined && char.myProfile !== null)
    ? char.myProfile : (s.myProfile || '')).trim();
  if (profile) {
    parts.push(`# 关于对方\n（这是他自己的说明，请一直记着）\n${profile}`);
  }

  // 「我的居住环境」：全局一份，讲清"他住的地方长什么样"。
  // 紧跟在「关于对方」后面：先说人，再说人待的地方，读起来是一路的。
  //
  // 加它的原因：模型没有环境设定时会自由发挥——凭空编窗外、编房间、编天气，
  // 跟用户实际的情况打架。长期记忆拦不住，因为记忆记的是"事件"，不是"环境"。
  // 同上（v1.21.47）：角色级优先，没设过才回落全局
  const env = String((char && char.myEnv !== undefined && char.myEnv !== null)
    ? char.myEnv : (s.myEnv || '')).trim();
  if (env) {
    // ⚠️ 加一条【仲裁语】（v1.21.33）：
    // 起因（用户提问）：世界书里也有「他的房子」这类词条时，两条会打架。
    // 而原来这条写的是「写到他家、房间、窗外、周边环境时【以此为准】」——
    // 世界书那边写的是「供你理解世界，不必主动复述」，措辞一硬一软，
    // 加上本段在【稳定前缀】（位置更靠前、更"根"），实测世界书会被压过去。
    // 现在显式声明优先级：专写住处的世界书条目 > 这条通用设定。
    parts.push(`# 他住的地方\n` +
      '（这是他居住环境的设定，和上面关于他的说明是一套。' +
      '写到他家、房间、窗外、周边环境时以此为准；' +
      '但【如果世界书里专门写了他的房子/住处/房间，以世界书那条为准】——' +
      '那条是他为这个地方单独写的，比这里的通用设定更准。' +
      '【没有写到的地方不要自己编】——不确定就写得模糊一点，' +
      '不要凭空添加这里没有的房间、家具、天气、外面的景物。）\n' + env);
  }

  const exp = [];
  const freq = effKaomojiFreq(char, s);
  const style = char.kaomojiStyle || s.kaomojiStyle || 'jp-soft';

  if (freq <= 0) {
    exp.push('- 你不使用任何颜文字（如 (´・ω・`) 这类符号组合）。');
  } else {
    exp.push(`- 你习惯的颜文字风格是${STYLE_NAME[style] || STYLE_NAME['jp-soft']}。`);
  }

  const ef = s.emojiFreq ?? 0;
  if (ef <= 0) exp.push('- 不要使用 emoji 表情符号。');
  else if (ef < 0.3) exp.push('- 很少使用 emoji，偶尔一两个即可。');
  else exp.push('- 可以适度使用 emoji。');

  exp.push('- ' + (LEN_HINT[s.verbosity] || LEN_HINT.medium));

  // 非对话描写：和上面的"回复长度"是两个独立上限。
  // 先讲清括号是干什么的，再说这一档写多细。
  //
  // ⚠️ 这里那句"两个上限各算各的"不能省。
  // 起因（用户实测反馈）：只给两条上限、不说它们互不占用时，模型会把
  // "说出口的话 150 字"当成【整条消息的总长度】，于是括号先把配额吃掉，
  // 表现就是"括号字数按最大那档算"。必须显式声明两者分开计数。
  const descLevel = s.descLevel || 'mid';
  const descLines = DESC_HINT[descLevel] || DESC_HINT.mid;
  if (descLevel === 'off') {
    exp.push('- 上面那条【说出口的话】的长度上限，和括号【完全分开算】——'
           + '括号不算在里面，也不会占用它的名额。');
    exp.push('- 这一档下【整条消息里不出现括号】，所以上面那个上限就是这条消息的全部内容。');
  } else {
    exp.push('- 上面那条【说出口的话】的长度上限，只管括号外面的部分。');
    exp.push('- 括号里写多少，由下面这条【单独】决定，不会占用上面那个名额；'
           + '反过来，括号写得多也不会让说出口的话变长。');
    exp.push('- 写法：括号里写动作、神态、语气、环境，括号外面才是你说出口的话。');
  }
  for (const line of descLines) exp.push('- ' + line);

  // 描写驱动力（v1.21.31 新增）：和 descLevel 并列，管【结构】不管【上限】。
  // ⚠️ descLevel === 'off' 时整条消息不许有括号 —— 那时这个开关无从谈起，跳过。
  // ⚠️ 与 low 档【冲突时要降级】（v1.21.32 修，复审 #7）。
  //
  // 起因：我上一版写了句「不冲突」，那是【假的】。
  // DESC_HINT.low 里「不要写环境，不要写心理」是【内容层面的禁止】，不是长度上限 ——
  // 而 DETAIL_DRIVE.max 要求「环境里哪里因此变了」「每一段都必须有感官锚点」，
  // 两者在同一条 system prompt 里【正面打架】。
  // 我的"上限 vs 结构正交"心智模型在 low 这一档不成立。
  //
  // 修法：low 档下把驱动【降级到 low】（它只要求"至少一个具体动作"，不与"不写环境"冲突），
  // 并如实说明降级原因，而不是塞一句假的"不冲突"。
  let drive = s.detailDrive || 'off';
  let driveDowngraded = false;
  // ⚠️ 降级范围要覆盖 mid（v1.21.34 修，复审 新4）。
  // 起因：上一版只挡 high/max，而 mid 的「动作链 + 具体感受」同样是【结构层面】的要求，
  // 与 low 的「每括号 ≤8 字、不写环境/心理」物理上写不下 → prompt 自相矛盾。
  // ⚠️ 降级判据改成【显式映射】，不再硬编码 low 特例（v1.21.36 修，复审 #6）。
  //
  // 起因：v1.21.34 只覆盖了 descLevel==='low'，而 mid/high 漏网 ——
  //   实测 `descLevel=mid（括号 ≤25 字） × detailDrive=max（三段式+感官锚点）`
  //   25 字里塞三段式，物理上写不下；且 myEnv 的「不要凭空添加房间/家具/天气」
  //   与 max 的「环境里哪里因此变了」正面打架。
  //
  // 现在按【字数预算】决定：各驱动档写全所需的下限 vs 当前上限能容纳的字数。
  const DRIVE_CAP = { off: null, low: 8, mid: 25, high: 60 };          // DESC_HINT 的硬上限
  const DRIVE_NEED = { off: 0, low: 8, mid: 25, high: 45, max: 60 };   // 各档写全所需下限
  const capChars = DRIVE_CAP[descLevel];
  if (capChars != null && capChars < (DRIVE_NEED[drive] || 0)) {
    drive = 'low';
    driveDowngraded = true;
  }
  const driveLines = DETAIL_DRIVE[drive] || DETAIL_DRIVE.off;
  if (driveLines.length && descLevel !== 'off') {
    exp.push('- 下面几条只管【括号里怎么写】，上面那个长度上限照旧生效。');
    if (driveDowngraded) {
      exp.push('- ⚠️ 上面把描写压得很短，所以下面这几条【按最低档执行】，别写长。');
    }
    for (const line of driveLines) exp.push('- ' + line);
  }

  if (s.splitMessages) {
    exp.push(`- 可以把一句话拆成 2-${s.splitMax || 3} 条短消息来发，每条之间用单独一行 \`---\` 分隔，模拟真人连着发几条。`);
  } else {
    exp.push('- 一次只发一条消息，不要用 --- 分隔。');
  }

  if (s.hesitation) {
    exp.push('- 适当用「……」表示停顿和迟疑，让语气更自然。'
           + '但它只能夹在句子里（「我……不知道」），【不能整条消息只有它】。');
  }

  // 【沉默必须写出来】（v1.21.22）。
  //
  // 起因（用户实测，反复出现）：她在"这时候不该说话"的戏里会整条只回一个「……」。
  // 用户看到的是一次次空白，只能不停点「重新思考」——
  // 而重试往往还是省略号，因为那是模型【主动】选的，不是被截断。
  //
  // 为什么会这样：角色Q 那种人设本来就写着她可以沉默；thinkMode 开着时对方整条
  // 都在括号里 = 他什么都没说；再叠上「hestitation 允许用省略号」的提示，
  // 模型就得出结论：此刻没有可说的话 → 输出省略号。
  // 实测那条的 reasoning 占了 completion 的 100%（155/155），全花在纠结上。
  //
  // 关键区分：【可以没有话说，但必须有内容】。
  // 不说话 ≠ 不回复。她要写的是"她怎么不说话"——
  // 平静地看着、把茶推过去、偏过头、屋里安静下来、她心里那一下是什么。
  // 这条对所有角色生效：它的意图是"别留白"，和具体人设无关。
  exp.push('- 【绝不允许】整条消息只有一个省略号、一个标点、或一片空白。');
  exp.push('- 就算你这时候【不该说话】——被捂住了嘴、不想开口、他没问你——也要写出来：'
         + '你在做什么、看着什么、手放在哪儿、屋里什么样、你心里那一下是什么。');
  exp.push('- 【不说话 ≠ 不回复】。你要写的是「你怎么不说话」，不是留一片空白。');
  // ⚠️ 这里【绝对不能给"最少写什么"的示例】（v1.21.23 修）。
  //
  // 第一版写的是「哪怕只是『（平静地看着他，没开口）』，也比一个省略号强得多」。
  // 用户实测评价：【太人机了，不如不输出】——
  // 那句"哪怕只是"在人类读来是下限，模型读来是【照这个写就对了】。
  // 于是她真的一路「平静地看着他」，比省略号还糟。
  //
  // 教训：给模型举例时，【它会把例子当成标准答案】。
  //       想要下限就描述"什么算不合格"，不要示范"勉强合格的样子"。
  exp.push('- 【注意】「（平静地看着他）」这种写法【信息量为零】——谁都写得出来，'
         + '不构成回复。要写就写【只有你才会有的那一下】：嘴角那点没压下去的意思、'
         + '故意慢半拍的呼吸、手指在袖口上捻了一下、心里冒出来又咽回去的那句。');
  // ⚠️ 补【取材方法】（v1.21.30，复审省略号专项 B）。
  //
  // 起因：上面的硬约束只有「不许写什么」（否定式），没有「那该写什么」（正面锚点）——
  // 模型知道不该留白，却缺锚点，于是【自己收敛到最安全、最通用的那句】：
  // 实测用户库里仅存的 2 条残留正是 `（只是看着他，没有开口）` ——
  // 那恰恰是 403 行被否掉的那句「人机句」。
  //
  // ⚠️ 但【不能给句式示范】（403-409 的教训：模型会把例子当标准答案）。
  // 这里给的是【取材方法】（从哪儿找内容）+【堵死它自己找到的收敛目标】，
  // 方向与 403 的教训相反、作用互补。
  exp.push('- 想不出写什么时，从这三处里挑一样写：① 你此刻在做什么（手放在哪儿、'
         + '身体什么姿势、周围什么样）；② 你看见他哪一点（他刚做了什么、什么表情）；'
         + '③ 你心里冒出来又咽回去的那句（写成「没说出口」，不要写成台词）。');
  exp.push('- 这三样都找不到，才说明这一轮真的没有可写的——那就把「没得写」本身写出来，'
         + '不要交一个省略号。');
  exp.push('- 【不要写】「（只是看着他，没有开口）」这一类——它对任何角色、任何场景都成立，'
         + '等于什么都没说。');

  exp.push('- 用口语聊天，不要用书面语、不要列 1234 条、不要写小标题、不要总结。');
  exp.push('- 不要提及自己是 AI、模型或程序。');

  parts.push(`# 表达方式\n${exp.join('\n')}`);

  // 视角锁定：单独成段放在最后，权重最高（模型对靠后的指令更敏感）。
  // 只在角色开了这个开关时才写，关着的时候提示词和以前完全一样（缓存不受影响）。
  // 叙事视角（v1.21.48）：'L1'~'L4' 四档；空 / 未设 = 不注入任何视角段落。
  //
  // ⚠️ 老数据的两条映射必须「一个字都不变」，因为这两段都在稳定前缀里：
  //    povLock=true  → L1（就是原来的 POV_HINT，逐字相同）
  //    povLock=false → 不注入（原来也是不注入）
  //    最容易写错的是把 false 也塞进 L1 —— 那等于给所有关着锁的角色凭空加了约束。
  const povKey = (s.povStyle && POV_STYLES[s.povStyle]) ? s.povStyle : (s.povLock ? 'L1' : '');
  if (povKey) {
    parts.push(`# 视角\n${POV_STYLES[povKey].join('\n')}`);
  }

  // 强制聊天模式：掰正"括号的语义"。
  // 和 povLock 一样放稳定前缀：它是长期规则、不随轮次变，
  // 开关不动时提示词逐字一致，前缀缓存照样命中（放变化段反而每轮都失效）。
  if (s.thinkMode) {
    parts.push(`# 关于括号\n${THINK_HINT.join('\n')}`);
  }

  // 「外貌」：她此刻的穿着和状态（角色级，随时会改）—— 【放最末尾】（v1.21.42）。
  //
  // 放最后的理由见本函数开头那段注释：它是这里变化最频繁的一项，
  // 一变就把它【后面】的全部作废。放末尾则改它只作废它自己。
  //
  // 空着 = 完全不注入，老角色的提示词一个字都不变。
  // 开关关掉 = 内容留着但也不注入（用户临时不想让她知道当前状态时用）。
  // 两层：appearanceLive（「立即生效」的临时覆盖）优先于 appearance（「保存」的长期基线）。
  // Live 为空时自动回落，所以用户点「清除」就等于回到长期那份。
  const look = ((s.appearanceLive || '').trim() || (s.appearance || '').trim());
  if (look && s.appearanceOn !== false) {
    parts.push(`# 你此刻的样子\n` +
      '（这是你现在身上穿的和当前的状态，【优先级最高】。' +
      '你设定里提到的服装是平时或别的场合的样子，此刻一律以这段为准；' +
      '两处不一致时，按这段写，不要按设定里那套写。）\n' +
      '写动作、神态、描写时也以此为准，不要写出和这里矛盾的东西' +
      '——比如这里说你没穿外套，就不要写拉外套的领子。\n' + look);
  }

  return parts.join('\n\n');
}

/**
 * 【本轮段】会变化的内容：记忆 / 时间 / 这一轮要不要颜文字
 * 放在消息列表的**最后**，这样前面的稳定前缀仍然能命中缓存
 */
/**
 * 一年按多少天算（v1.21.43）。
 *
 * ⚠️ 这只是【显示用的换算率】，day 才是唯一的数据源 —— 不新增 year 字段。
 *    两套数并存迟早对不上（改了年没改天，或者反过来）。
 */
export const DAYS_PER_YEAR = 365;

/**
 * 天数的显示文案（v1.21.43 起大跨度带「年」）。
 *
 * 为什么要有它：天数上限放宽到 9999999 之后，「第 365250 天」这种写法
 * 读起来没有尺度感 —— 看到「第 1001 年 250 天」才知道这是千年之后的事。
 *
 * ⚠️ day ≤ 365 时【一个字都不改】，和以前完全一样。这一条很重要：
 *    提示词里的时间串参与前缀缓存，老角色（天数都小）不能因为这次改动而失配。
 *
 * 换算：第 1 年 = 第 1~365 天，第 2 年 = 第 366 天起（所以是 (d-1)/365 而不是 d/365）。
 *
 * 放在 persona.js 而不是 app.js：提示词里两处都要用它（"现在的时间"和下面的锚点表），
 * 分开写两份迟早会漂移。
 */
export function dayLabel(day) {
  const d = Math.max(1, Math.floor(Number(day) || 1));
  if (d <= DAYS_PER_YEAR) return '第 ' + d + ' 天';
  const y = Math.floor((d - 1) / DAYS_PER_YEAR) + 1;
  const rest = ((d - 1) % DAYS_PER_YEAR) + 1;
  return '第 ' + y + ' 年 ' + rest + ' 天';
}

/**
 * 把话题切成"用来比对的词"（v1.21.56）。
 * 中文没有空格，用【二元组】—— 「咖啡店」→ 咖啡/啡店，够用且不需要分词库。
 * 英文/数字按整词。返回 Set，方便 O(1) 判重。
 */
function topicGrams(topic) {
  const s = String(topic || '');
  const out = new Set();
  for (const chunk of (s.match(/[\u4e00-\u9fff]+/g) || [])) {
    if (chunk.length === 1) out.add(chunk);
    for (let i = 0; i + 1 < chunk.length; i++) out.add(chunk.slice(i, i + 2));
  }
  for (const w of (s.match(/[A-Za-z0-9]{2,}/g) || [])) out.add(w.toLowerCase());
  return out;
}

/**
 * 从记忆里挑出【跟眼下这段话最相关】的那几条（v1.21.56）。
 *
 * 以前是 memories.slice(-24)：纯按最新。这套在几十轮内没问题，
 * 几百轮之后就成了"她记得结论、细节对不上"——你正在聊的那件事被更晚的 24 条挤在外面。
 *
 * 不上向量检索（要引依赖、还要每轮算 embedding）：先做**关键词重合 + 新近度 + pinned**。
 *   相关度 = 命中词数 × 3      ← 主导项
 *   pinned = 用户点名要记的 × 2 ← 那是他明确要求记住的，不该被挤掉
 *   新近度 = 越靠后越大 × 0.5   ← 只做微调
 * ⚠️ 新近度权重刻意压得很低：给高了会把"最近但无关"的顶上来，等于回到老行为。
 *
 * @param {Array} memories 记忆数组（按时间追加，最后一条最新）
 * @param {string} topic 眼下这段话（一般是本轮用户输入 + 最近一两条）
 * @param {number} limit 取几条（默认 24，与旧行为一致）
 * @returns {Array} 挑出来的记忆，**按原时间顺序**排回去（注入给模型的文本读起来才不乱）
 */
export function rankMemories(memories, topic, limit = 24) {
  const list = Array.isArray(memories) ? memories : [];
  if (!list.length) return [];
  // 本来就不超过上限 → 不折腾（也避免了"打分把顺序打乱"这种没必要的副作用）
  if (list.length <= limit) return list.slice();
  // ⚠️ pinned 是【保底进】，不参与打分争夺（v1.21.56 第一版就栽在这儿）。
  //
  // 起初把它做成 +2 分的加成，可"关键词命中"一条就是 +3 ——
  // 话题里只要凑够 24 条沾边的记忆，用户点名要记住的那条就会被挤出去。
  // 实测：记忆里有 29 条含「无关」的旧事、当轮话题里也有「无关」，
  // 那条 pinned 就排到了第 30 名、直接落选。
  // 「记住这个」是他明确下的指令，不该输给任何打分。
  const isPinned = (m) => !!(m && m.freq === 'pinned');
  const pinnedList = list.filter(isPinned);
  const pinnedSet = new Set(pinnedList);
  const rest = list.filter(m => !pinnedSet.has(m));
  const room = Math.max(0, limit - pinnedList.length);   // pinned 先占名额，剩下的才打分
  const grams = topicGrams(topic);
  const scored = rest.map((m, i) => {
    const text = String((m && m.text) || '');
    let hit = 0;
    for (const g of grams) if (text.includes(g)) hit++;
    // 新近度权重刻意压得很低：给高了会把"最近但无关"的顶上来，等于退回老行为
    const recency = rest.length > 1 ? i / (rest.length - 1) : 1;
    return { m, i, score: hit * 3 + recency * 0.5 };
  });
  // 同分时按原始顺序（稳定，不会因为排序实现不同而抖）
  scored.sort((a, b) => (b.score - a.score) || (a.i - b.i));
  const keep = new Set(pinnedList);
  for (const x of scored.slice(0, room)) keep.add(x.m);
  return list.filter(m => keep.has(m));   // 按原时间顺序回去
}

export function buildTurnNote(char, s, ctx = {}) {
  const { memories = [], useKaomoji = false, clock = null, clockLocked = false, rolling = '',
          clockState = null, prevStory = null, scene = '', topic = '', speaker = '',
          // 群聊「小说式一幕」（v0.4.1）：这一轮不只是一个人说一句，而是把整幕写下来。
          // narrative=true 时放开"只写你自己"，改成"谁做什么、谁说什么"都能写；
          // memberNames 是这一幕的在场名单，用来约束【名字】只能用这几个。
          narrative = false, memberNames = [], named = false,
          // 篇幅档位（v0.4.1.1）：用户实测"聊两轮 token 就没了"，
          // 所以这一幕写多长必须能调 —— 小说感是拿 token 换的，得让他自己选换多少。
          sceneLen = 'mid',
          // 群里要不要旁白（v0.4.1.6）：关掉时不要求场面描写，改成"每行都得有名字"
          narrLines = true } = ctx;
  const parts = [];
  // ⚠️ 世界书放在【本轮段最前面】（v1.20.20 调整）。
  //
  // 起因（2026-09-29 实测 角色Q 195 轮 usage）：命中集一变，它【后面】的整段
  // （时间标记 / 记忆）就全部重新计费。9 个异常轮的 prompt_cache_hit_tokens
  // 恰好停在 6784 / 6144 —— 正是「稳定前缀 + 历史 + clock + rolling」的长度，
  // 也就是世界书之前那一段，每轮白花 4000~5800 token。
  //
  // 挪到最前面之后，即使命中集偶尔变化，被作废的也只有它自己后面这几十字，
  // 而不是拖着一整段记忆一起重算。语义上也没损失：
  // 背景设定本来就该在读时间/记忆之前先建立。
  //
  // ⚠️ 绝不能放进 buildStablePrompt —— 它随对话内容变化，
  //    进了稳定前缀就等于每轮都让缓存失效，token 直接翻十倍。
  const wbHits = ctx.worldbook || [];
  // 位置分两档（v1.21.51）：「背景」档放本轮段最前（就在下面）；
  // 「临场」档放到靠后（记忆之后、本轮要求之前），见本函数末尾。
  // 常驻条目（pos === 'always'）不走这里 —— 它们进稳定前缀，见 buildStablePrompt。
  const wbFront = wbHits.filter(h => h && h.pos !== 'tail');
  if (wbFront.length) {
    const body = wbFront.map(h => '【' + h.title + '】\n' + h.content).join('\n\n');
    parts.push(`# 相关设定\n（这些是背景设定，供你理解世界，不必主动复述，聊到相关话题时自然地用。）\n\n${body}`);
  }


  // 群聊：这一轮轮到谁说话（v0.4.0）。
  // ⚠️ 只在这一轮段里说 —— 轮次每轮都在变，放进稳定前缀等于每轮让缓存作废。
  const spk = String(speaker || '').trim();
  if (spk) {
    // ⚠️ 措辞在 v0.4.0 复查时改了（群聊诊断文档 3.2）。
    //    原来只说"这一轮只写「乙」一个人的反应"，没告诉它【历史里谁是谁】——
    //    而历史现在每条都带【名字】前缀（见 app.js 的 composeApiMsgs），
    //    所以这里必须点明那个前缀是什么意思，否则模型会把前缀当正文的一部分。
    //    最关键的是第一句：直接告诉它"你现在是谁"，而不是让它从上一轮的
    //    语气里自己猜 —— 猜的结果就是第二个人顶着第一个人的身份说话。
    const roster = (Array.isArray(memberNames) ? memberNames : []).filter(Boolean);
    // 这一幕最多几个人开口：跟着【抽到的名单】和篇幅档位走（v0.4.1.6）
    const CN_NUM = { 1: '一', 2: '两', 3: '三' };
    const ROSTER_MAX = Math.max(1, Math.min(roster.length, sceneLen === 'short' ? 2 : 3));
    const sizeHint = '最多' + (CN_NUM[ROSTER_MAX] || '三') + '个人开口，整幕 '
      + ({ short: '120~220 字', mid: '200~350 字', long: '350~600 字' }[sceneLen] || '200~350 字');
    if (narrative && roster.length > 1) {
      // ⚠️ 这一段和 else 那条【是互斥的两套写法】，别把它们揉在一起：
      //    else 那套是"这一轮只有你一个人"，用来治身份串台；
      //    这一套是"把这一整幕写下来"，用来出小说感。
      //    两套的约束正好相反（一个禁"替别人说话"，一个要求"写所有人的动作"），
      //    揉在一起模型两头都做不到，会退化成流水账。
      parts.push('# 这一幕怎么写\n'
        + (named ? '**他这一句就是冲着你说的，你必须接话。**\n' : '')
        + '**你现在是「' + spk + '」**，这一场里有 ' + roster.join('、') + '。把**这一幕**写下来。\n'
        + '要点不是"每个人各说一句"，而是**她们之间真的在互动** —— 这是群聊唯一的优势。\n'
        + '· 像写小说那样写：谁做了什么、谁说了什么、周围有什么变化\n'
        + '· **换人说话就另起一行，行首用【名字】标出来**（例如【乙】后面接她说的话）。'
        + '名字只能用这几个：' + roster.join('、') + '\n'
        + '· **后开口的人要接住前一个人的话** —— 同意、反驳、追问、打岔、替她补充、笑她，都行。'
        + '不许各说各的；也不许所有人都一个意见（那读起来是假人）\n'
        + '· **旁白多写"人对人"的动作和反应**（她斜了她一眼、把杯子往她那边推、被呛得咳了两下），'
        + '不只是天气和环境 —— 活力就来自这里\n'
        + '· **这一幕结束时，事情要往前走一点**：关系、信息、情绪、下一步的打算，'
        + '至少要有一样和开口之前不一样\n'
        // ⚠️ v0.4.1.4：这句原来是【反的】—— 它要求"一个人连着说的几句放在同一行里"，
        //    而解析器（app.js 的 splitBySpeaker）本来就是"同名多行各自成一段"。
        //    提示词和解析器互相抵消，用户要的"一个人连发几条"永远出不来。
        + '· 同一个人连着说几句，就【写几行、每行都以她的名字开头】—— 一次把一大段塞进一行反而假\n'
        // ⚠️ v0.4.1.6：解析器（app.js 的 splitBySpeaker）改了 —— 没标名字、又没用
        //    括号包住的行，会算成【上一个说话人】说的。提示词必须跟解析器说同一件事，
        //    否则"旁白"会被挂到某个人嘴上。（这两句是一对，改一句不改另一句就是互相打架。）
        + (narrLines
            ? ('· **场面描写整行用括号包起来**（例如：（她把杯子往桌上一放））；'
               + '没标名字、又没用括号包住的行，系统会算成【上一个说话人】说的\n'
               + '· 旁白只写**所有人在场都能看见的**东西：环境、天气、公共场面。'
               + '某个人自己的动作、表情、心里想的，写在她那一段里，别丢给旁白\n'
               + '· 旁白里**不要出现不指名的「她」** —— 旁白没有说话人，写「她」没人知道是谁，要写就直接写名字\n')
            : '· **这个群关掉了旁白：每一行都必须以说话人的名字开头**；'
              + '没标名字的行会被算成上一个说话的人说的\n')
        + '· 历史里每条开头的【名字】标的是**那句话是谁说的** —— '
        + '带别人名字的那些**不是你说的**，是别人说的，你只是听见了\n'
        + '· 必须有「' + spk + '」的一段（这一轮从她起头）\n'
        // ⚠️ v0.4.1.6：这句原来写死"最多三个人"，而它是【上限】不是目标 ——
        //    群里正好两个人时，模型把它当成"两个人都要来一段"，
        //    于是 54% 的轮次都是严格二人转（用户拿 26 轮记录数出来的）。
        //    现在上限跟着【这一幕抽到的名单】走：只抽到两个人，就说最多两个人。
        + '· **' + sizeHint + '** —— 只写上面点到名字的那几个，'
        + '别把在场的人挨个写一遍（那是点名册不是小说）\n'
        + '· 每个人只按**她自己那份设定**说话：语气、口癖、称呼都别串味\n'
        + '· 结尾可以留个钩子（有人看向他、问了句什么），让他有话可接');
    } else {
      parts.push('# 这一轮你演谁\n'
        // ⚠️ v0.4.1.6：这一套原来没有"你必须接话"那句，而它现在不只是"关掉小说模式"
        //    时才走 —— 这一幕只抽到 1 个人时也走它。用户点了名（@她 / 「她：」）时，
        //    那句提醒必须还在，否则"点名的意愿"在单人模式下反而没人告诉模型。
        + (named ? '**他这一句就是冲着你说的，你必须接话。**\n' : '')
        + '**你现在是「' + spk + '」。** 这一轮只写' + spk + '一个人的反应。\n'
        + '· 历史里每条开头的【名字】标的是**那句话是谁说的** —— '
        + '带别人名字的那些**不是你说的**，是别人说的，你只是听见了\n'
        + '· 不要替别人说话，也不要写别人的动作、心理和台词\n'
        + '· 不要写「某某说：」这种报幕，直接写内容\n'
        + '· 别人插话、打断都不该由你来写 —— 这一轮只有你\n'
        + '· 轮到你之前发生的事你都看见了，可以接话，但别复述\n'
        + '· 你只按**你自己那份设定**说话：语气、口癖、称呼都跟着它走，别串到别人身上');
    }
  }

  // 临时场景（v1.21.47）：用户当下给这一段对话设的场景。
  // ⚠️ 它只在【本轮段】里 —— 改得很勤，放进稳定前缀就是每改一次让整段重新计费。
  // 位置：世界书之后、时间之前。比世界书更"近"，但不该压过剧情时间。
  const sceneNow = String(scene || '').trim();
  if (sceneNow) {
    parts.push('# 当前场景\n'
      + '（这是他这会儿设定的场景，你们这一段对话就发生在这里。'
      + '按它写环境、氛围和正在发生的事；'
      + '但不要复述它、也不必每句都提——像本来就身处其中那样自然地写。）\n'
      + sceneNow);
  }

  // 关键：这里原来注入的是真实世界时间，会跟用户在括号里写的剧情时间打架，
  // 导致它自己乱算日子、跨天就把前面的事忘了。改成注入剧情时间线。
  parts.push(clock
    ? `# 现在的时间\n剧情里现在是 **${clock}**。`
      + (clockLocked
        ? `**这个时间是定死的**，他说什么都不会改变它。他要是提到跟这个对不上的时间`
          + `（比如明明才过了一会儿就说到了第二天），一律以这个为准，不要顺着改口，也不要去圆。\n`
        : '')
      + `这是你们对话内的剧情时间，不是真实世界的时间；`
      + `注意：日子翻篇不等于前面的事作废——`
      + `他之前说过的、答应过的，你照样记得，该提就提。`
      // ⚠️ 相对时间【锚点表】（v1.21.37 新增，复审 问题②）。
      //
      // 起因（用户实测 + 子代理决定性证据）：
      //   整份 prompt 里「后天」的【定义次数 = 0】——
      //   原来只有一句「他说『昨天』『明天』『等会儿』都按这条线算」，
      //   而「这条线」只是【一个点（第 N 天）】，不是换算表。
      //   实测案例：第1天定「后天」= 第3天，到第2天、第3天她仍当"从今天起算的后天"。
      //   备份里「昨天」出现 93 次、「明天」83 次、「后天」15 次，全靠模型自己猜。
      //
      // ⚠️ 必须处理【跳日】：用户备份里第 4 天说的「后天」在第 6 天才兑现（第 5 天缺失），
      //   所以不能只说 "day+2"，要说明「以说那句话的那天为基准」。
      //
      // ⚠️ 「后天」绝不能加进 detectClock 的 dayRules —— 那是【指认】未来某天（约定），
      //   不是【推进】时间。加了会让约定变成推进，语义完全错。
      + (clockState && typeof clockState.day === 'number'
        ? `\n\n【相对时间怎么算 —— 按「说那句话的那天」锚定，不要按「从今天起」算】\n`
          // ⚠️ 大跨度时把「年」也写出来（v1.21.43）。
        //    上面"现在的时间"那段用的是 dayLabel（第 1001 年 250 天），
        //    这里要的是【精确天数】做加减（昨天 = day-1），所以不能换成 dayLabel ——
        //    但同一个日子出现两种写法，不点破的话模型可能对不上。
        //    day ≤ 365 时【一个字符都不加】，老角色的提示词与改动前逐字相同（前缀缓存不受影响）。
        + `· 现在是第 ${clockState.day} 天`
        + (clockState.day > DAYS_PER_YEAR ? `（也就是上面说的「${dayLabel(clockState.day)}」）` : '')
        + `。站在这一天的角度：`
          // ⚠️ v1.21.38 修：第 1 天时 day-1 = 0，会拼出「昨天=第 0 天」——
          // 而第 0 天在设定里不存在（清空聊天时 day 重置为 1，loadClock 也按 1 起）。
          // 模型收到不存在的日期锚点，在「她刚说完昨天的事」时会照抄「第 0 天」。
          // 第 1 天 = 故事刚开始，还没有「昨天」，单独给文案，不要机械输出 day-1。
          + (clockState.day <= 1
              ? `今天=第 1 天，明天=第 2 天，后天=第 3 天。\n`
                + `· ⚠️ 现在才第 1 天，【还没有「昨天」】。他若提到「昨天」的事，那是故事开始之前发生的；你不要用「第 0 天」这种不存在的说法去指代，直接说「之前」或照他说的内容回应就行。\n`
              : `昨天=第 ${clockState.day - 1} 天，今天=第 ${clockState.day} 天，`
                + `明天=第 ${clockState.day + 1} 天，后天=第 ${clockState.day + 2} 天。\n`)
          + `· ⚠️ 但【他说的「后天」是哪一天，要看他那句话是第几天说的】：`
          + `第 1 天说的后天是第 3 天，第 3 天说的后天是第 5 天 —— 【不是同一个日子】。\n`
          + `· 历史消息开头的【第 N 天 …】就是那句话的日期，照着算。\n`
          + `· 你许下的、或他答应过的时间点，要按【当时那天算出的绝对日子】记住；`
          + `之后提起来必须指向同一个日子，不要重新起算。\n`
          // ⚠️ 跳日说明（v1.21.37，复审 P2-1）：
          // 备份实测 day 序列 1 2 3 4 [5 缺失] 6 7 …，而 clockGap 只说「过了 2 天」，
          // 模型会把「跳过的日子」当成「发生过什么但我不知道」去圆，反而编内容。
          + `· ⚠️ 他可能【手动调过时间】—— 所以天数跳跃（比如从第 4 天直接到第 6 天）`
          + `通常只是他拨了时间条，不代表中间发生了什么大事。`
          + `不要在对话里追问或解释那些跳过日子的去向。`
          + (clockLocked ? `\n· 时间是定死的：他要是推进得太快或太慢，以这里的第几天为准。` : '')
        : '')
      // ⚠️ 补「时间会流逝」这条规则（2026-09-27 修）。
      //
      // 起因（用户实测）：他在描写里写了「过了半小时都没松手」，
      // 而提示词只说了「现在几点」，【没有一句说"时间会往前走"】——
      // 于是模型要么完全当没看见（继续用「刚才」的语气），
      // 要么自己编一个数字（「我数着的，最多二十分钟」）。
      // 两种都别扭：前者像时间冻住了，后者是它凭空造事实。
      //
      // 现在明确三件事：
      //   ① 他描写里提到的时间跨度要认（那是他推进剧情的动作）
      //   ② 认了之后【反应要跟着变】，不能还停在半小时前的语气
      //   ③ 【不许自己编数字】—— 他没说多久，你就不要替他算
      // C1（2026-09-28 新增）：把「上一条 → 现在」的跨度显式写出来。
      //
      // 起因（用户实测）：他手动把时间从「第 2 天 11:24」改成「第 2 天 11:30」，
      // 期待她按"过了 6 分钟"来反应。但提示词里【只有当前时刻】——
      // 她自己看不到"上一条是几点"，历史消息也不带时间（buildHistory 只返回 role/content）。
      // 于是她要么按新时间随口回，要么继续说"刚才"（对她来说时间永远只是"现在这一刻"）。
      // 结果就是用户反复点「重新思考」，她还是一直说"你昨天发的消息"。
      //
      // 这一段把差值直接算好给她，只在实际有跨度时出现（同一时段内不写，省 token）。
      + clockGap(clockState, prevStory)
      + `\n【时间会往前走 —— 这条要主动跟上】\n`
      + `· 他要是写了时间过去多久（「抱了半小时」「沉默了一会儿」「过了好一阵」「天黑了」），`
      + `  【那是他在推进剧情，你要认，反应也要跟着变】—— 不能还停在刚才的语气上。\n`
      + `· 该怎么表现：写身体的变化（手麻了、腿坐僵了、背上汗干了）、写你察觉到的变化`
      + `（光挪了位置、外面的声音停了、他呼吸慢下来了）、或者直接说出来（「都这么久了」）。\n`
      + `· ⚠️ 【不要自己编数字】。他没说多久，你就不要替他算出一个具体分钟数。`
      + `  可以说「好一阵」，不要说「二十三分钟」。\n`
      + `· 如果他写的时间和当前时段对不上（明明才过了一会儿，却说到第二天了），`
      + `  以【上面那个设定时间】为准，不要顺着改口、也不要去圆。`
    : `# 现在的时间\n${fmtTime(new Date())}`);

  // ⚠️ 「本轮要求」（颜文字）【挪到了本函数最末尾】（v1.21.42）。
  //
  // 它是这里【唯一每轮都可能翻转】的一项（decideKaomoji 每轮重判），
  // 原来排在滚动摘要 / 历史时间标记 / 记忆之前 —— 一翻转就把后面三项全部作废。
  // 按"变化越频繁越靠后"的规则，它该在最后。

  // 滚动摘要：更早的对话（已经归档、不再原样发送的那部分）。
  //
  // 为什么需要它：msgs.list() 默认不返回已归档消息，
  // 所以归档 = 那段对话从此不再进入上下文。没有这段摘要，
  // 她只剩记忆里零散的事实条目，前情连续性直接断掉。
  //
  // ⚠️ 措辞要强调"这是你亲历的过去"，否则模型会把它当背景资料，
  //    回话时不带上，等于白注入。
  if (rolling) {
    parts.push(
      '# 之前发生过的事\n'
      + '（以下是你们更早时候的经历，已经浓缩成一段。这些都是【你亲身经历过的】，\n'
      + '不是别人告诉你的设定。提到相关的人、事、约定时，自然地带出来，不要复述这段本身。）\n\n'
      + rolling
    );
  }

  // C-B：历史里带时间标记时要说明它是什么，并禁止模仿。
  // 不说的话模型会以为那是"叙述格式"，在自己的回复里也写【第 4 天】——
  // 角色E这种动作流人设尤其容易（模型本来就爱套用看到的句式）。
  if (s.historyTime !== false) {
    parts.push(
      '# 历史里的时间标记\n'
      + '（上面每条对话开头偶尔会出现 **【第 3 天 下午】** 这种方括号，那是系统标的时间，\n'
      + '告诉你那句话是什么时候说的，方便你算过了多久。\n'
      + '**你自己回复时不要写这种标记**，那是给系统用的，不是说话的方式。）'
    );
  }

  // 记忆放在最后：模型对结尾的内容注意力最高。原来放在最前面，
  // 会被几千字的人设淹没，等于没写。
  if (s.longMemory && memories.length) {
    // ⚠️ v1.21.56：从「最近 24 条」改成「跟眼下这段话最相关的 24 条」。
    //
    // 起因：纯按最新挑，几百轮之后就变成"她记得结论、但细节对不上"——
    // 你正在聊的那件事可能躺在第 30 条上，而它前面躺着 24 条无关的旧事。
    // 条数上限【没变】（还是 24，token 开销一样），只是挑得更准。详见 rankMemories。
    //
    // ⚠️ v0.4.1.4：群聊里再加一层【视角】过滤。
    //    群的记忆原来全群共用一份、连主语都没有（标题写死"你记得关于他的事"），
    //    于是甲私下的事会被读成"大家都知道"。现在每条记忆可以带 who（属于谁的视角）：
    //      · 当前发言人自己的（最多 16 条）
    //      · 全群共识（who 为空，最多 8 条）—— 老数据没有 who，一律当共识
    //    别人视角的记忆【不注入】：把甲的私事塞进乙的嘴里，比"她不知道"更糟。
    //    条数上限仍是 24，token 不涨。单聊时 memWho 是空串，走 else，行为和以前一模一样。
    const selfId = String(ctx.memWho || '');
    const selfName = String(ctx.memWhoName || '');
    if (selfId) {
      const mine = memories.filter(m => m && m.who === selfId);
      const shared = memories.filter(m => m && !m.who);
      const minePick = rankMemories(mine, topic, 16);
      const sharedPick = rankMemories(shared, topic, 8);
      const keep = new Set(minePick.concat(sharedPick));
      const picked = memories.filter(m => keep.has(m));   // 按原时间顺序回去
      if (picked.length) {
        const blocks = [];
        if (minePick.length) {
          blocks.push('# 你（' + (selfName || '她') + '）自己看在眼里的事\n'
            + minePick.map(m => '- ' + m.text).join('\n'));
        }
        if (sharedPick.length) {
          blocks.push('# 这个群里大家都知道的事\n'
            + sharedPick.map(m => '- ' + m.text).join('\n'));
        }
        // ⚠️ 最后那句只在【真有"她自己看在眼里的事"】时才说 ——
        //    乙一条自己的记忆都没有时还写"上面那些只有你知道"，
        //    上面根本没有那一段（e2e-groupmem 抓到的）。
        blocks.push('（这些是你本来就记得的，不用复述。聊到相关的话题时，自然地带出来就行。'
          + (minePick.length
              ? '\n上面「你自己看在眼里的事」只有你知道 —— 别当成大家都知道的事说出来。)' 
              : '）'));
        parts.push(blocks.join('\n\n'));
      }
    } else {
      const picked = rankMemories(memories, topic, 24);
      const body = picked.map(m => '- ' + m.text).join('\n');
      parts.push('# 你记得关于他的事\n' + body + '\n\n这些是你本来就记得的，不用复述。聊到相关的话题时，自然地带出来就行。');
    }
  }

  // 世界书「临场」档（v1.21.51）：放到本轮段靠后的位置 —— 记忆之后、本轮要求之前。
  // 位置越靠后，模型越容易把它当成"眼下正在生效"的东西，适合写口吻、正在发生的事；
  // 想当背景资料用的条目留在上面「相关设定」那一档。
  // ⚠️ 不放到最末尾：「本轮要求」（颜文字）每轮都可能翻转，它后面不该再有内容。
  const wbTail = wbHits.filter(h => h && h.pos === 'tail');
  if (wbTail.length) {
    const body = wbTail.map(h => '【' + h.title + '】\n' + h.content).join('\n\n');
    parts.push('# 临场设定\n'
      + '（这几条是眼下正在生效的，这一轮按它们来，不用复述。）\n\n'
      + body);
  }

  // 「本轮要求」：颜文字开关 —— 【放最末尾】（v1.21.42）。
  //
  // 放最后的理由见本函数开头：它是本段里唯一每轮都可能翻转的一项。
  // 放末尾之后，它翻转时后面【没有任何内容】需要重算。
  // （注：这一段整体在历史之后，所以它本身能否进缓存取决于 prompt 的整体布局；
  //   但至少它不再是"一翻转就拖累后面三项"的那一块。）
  if (effKaomojiFreq(char, s) > 0) {
    parts.push(useKaomoji
      ? '# 本轮要求\n这一次的回复里，在合适的位置加一个颜文字。只加一个，不要堆叠。'
      : '# 本轮要求\n这一次不加颜文字，用纯文字自然表达。');
  }

  return parts.join('\n\n');
}

/** 按 --- 拆分多段消息 */
export function splitMessages(text, max = 3) {
  if (!text) return [text];
  const segs = text.split(/\n\s*-{3,}\s*\n/).map(x => x.trim()).filter(Boolean);
  if (segs.length <= 1) return [text.trim()];
  const lim = Math.max(1, Number(max) || 1);
  if (segs.length <= lim) return segs;
  // 超出上限的段合并进最后一段。以前是 segs.slice(0, max) —— 模型多拆一段，
  // 最后那段内容就凭空没了。
  return segs.slice(0, lim - 1).concat(segs.slice(lim - 1).join('\n\n'));
}
